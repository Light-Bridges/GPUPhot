#!/usr/bin/env python3
"""Latency figures cited by the prose, under the per-column epoch split.

Runs AFTER switching over (GPUPHOT_TABLES_POSTFIX=1) and produces in data/:
  prose_latency_summary_by_gpu.csv   one row per card
  prose_latency_ratio_by_cell.csv    one row per cell, with the py3.12/py3.8 ratio
  prose_latency_coverage_delta.csv   cells each column gains or loses against August

Exists because those figures are cited in several places in the text, and
until now they had to be recalculated by hand every time the epoch split
changed, which is exactly how discrepancies creep in between what the table
says and what the paragraph says.

Usage: GPUPHOT_TABLES_POSTFIX=1 python build_prose_latency_summary.py
"""
import os
import sys

import pandas as pd

BASE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, BASE)
import generate_manuscript_tables as T  # noqa: E402

DENSE = 'QHY411-3_Lum_131k'   # 134,206 sources dense field cited in manuscript
ARMS = ('py38_baseline', 'py312_cuml_adaptive')


def _medians(labels, gpu_cols, by_epoch):
    """Median per (GPU, image) for each arm."""
    out = {}
    for lab in labels:
        d = (T.load_benchmark_by_epoch(lab, gpu_cols) if by_epoch
             else T.load_benchmark(lab, csv_path=T.BENCHMARK_CSV))
        d = d[d['gpu_label'].isin(gpu_cols)]
        out[lab] = d.groupby(['gpu_label', 'image_label'])['execution_time'].median()
    return out


def main():
    gpus = list(T.GPU_EPOCH)
    nuevo = _medians(ARMS, gpus, by_epoch=True)
    agosto = _medians(ARMS, gpus, by_epoch=False)

    cell = pd.concat([nuevo[ARMS[0]].rename('py38'),
                      nuevo[ARMS[1]].rename('py312')], axis=1).dropna().reset_index()
    cell['ratio'] = (cell.py312 / cell.py38).round(4)
    cell['py38_faster'] = cell.ratio > 1
    cell['epoch'] = cell.gpu_label.map(T.gpu_epoch)
    cell = cell.sort_values(['gpu_label', 'image_label'])

    filas = []
    for g, s in cell.groupby('gpu_label'):
        d38 = nuevo[ARMS[0]].get((g, DENSE), float('nan'))
        d312 = nuevo[ARMS[1]].get((g, DENSE), float('nan'))
        filas.append(dict(
            gpu=g, epoch=T.gpu_epoch(g),
            paired_cells=len(s),
            py38_faster_count=int(s.py38_faster.sum()),
            median_ratio=round(s.ratio.median(), 3),
            min_ratio=round(s.ratio.min(), 3), max_ratio=round(s.ratio.max(), 3),
            dense_py38_s=round(d38, 2) if pd.notna(d38) else '',
            dense_py312_s=round(d312, 2) if pd.notna(d312) else '',
            median_all_cells_py312_s=round(
                nuevo[ARMS[1]].loc[g].median(), 2) if g in nuevo[ARMS[1]].index.get_level_values(0) else ''))
    por_gpu = pd.DataFrame(filas)

    glob_med = cell.ratio.median()
    cab = (f'# Latency summary figures for manuscript prose by GPU and epoch.\n'
           f'# Generated by build_prose_latency_summary.py. Campaign: '
           f'{"POST-FIX (per-column epoch mapping)" if T.USE_POSTFIX_CAMPAIGN else "August"}.\n'
           f'# Paired cells comparison (both py3.12 and py3.8 measured):\n'
           f'#   Total paired cells: {len(cell)}\n'
           f'#   py3.8 faster in: {int(cell.py38_faster.sum())} of {len(cell)}\n'
           f'#   Global median ratio py3.12/py3.8: {glob_med:.3f} '
           f'(py3.12 {100*(glob_med-1):+.1f}% vs py3.8)\n'
           f'# epoch: data campaign source (GPU_EPOCH in generate_manuscript_tables.py).\n'
           f'# dense_*: 134,206 sources field ({DENSE}).\n')
    open(os.path.join(BASE, 'data', 'prose_latency_summary_by_gpu.csv'), 'w').write(
        cab + por_gpu.to_csv(index=False))
    open(os.path.join(BASE, 'data', 'prose_latency_ratio_by_cell.csv'), 'w').write(
        '# Ratio py3.12/py3.8 per cell with per-column epoch mapping.\n'
        '# ratio > 1.0 indicates py3.8 is faster.\n'
        + cell.round(3).to_csv(index=False))

    # Coverage delta against August campaign
    cov = []
    for lab in ARMS:
        a = agosto[lab].reset_index().groupby('gpu_label')['image_label'].apply(set)
        b = nuevo[lab].reset_index().groupby('gpu_label')['image_label'].apply(set)
        for g in gpus:
            sa, sb = a.get(g, set()), b.get(g, set())
            if not sa and not sb:
                continue
            cov.append(dict(arm=lab, gpu=g, epoch=T.gpu_epoch(g),
                            august_cells=len(sa), current_cells=len(sb),
                            dropped='|'.join(sorted(sa - sb)) or '',
                            gained='|'.join(sorted(sb - sa)) or ''))
    open(os.path.join(BASE, 'data', 'prose_latency_coverage_delta.csv'), 'w').write(
        '# Cell coverage comparison: cells gained or dropped per column vs August campaign.\n'
        '# Tracks cell completeness across remeasured hardware arms.\n'
        + pd.DataFrame(cov).to_csv(index=False))

    print('\n== SIGN CHANGES vs August (py3.8 no longer faster) ==')
    hubo = False
    for g in gpus:
        try:
            ra = (agosto[ARMS[1]].loc[g] / agosto[ARMS[0]].loc[g]).dropna().median()
            rn = (nuevo[ARMS[1]].loc[g] / nuevo[ARMS[0]].loc[g]).dropna().median()
        except KeyError:
            continue
        if pd.notna(ra) and pd.notna(rn) and (ra > 1) != (rn > 1):
            print(f'   {g}: August {ra:.2f}x -> now {rn:.2f}x  SIGN CHANGE'); hubo = True
        if not hubo:
            print('   none')

    print('\n== CARD RANKING ==')
    grupos = [('Datacenter (19 common images)',
               ['H100 (80 GB)', 'A100 (80 GB)', 'L40S (48 GB)']),
              ('All x86 hosts, on their common cells',
               [g for g in gpus if 'Orin' not in g])]
    for titulo, cards in grupos:
        print(f'   -- {titulo}')
        for nom, src in (('August', agosto), ('Current', nuevo)):
            m = src[ARMS[1]]
            m = m[m.index.get_level_values(0).isin(cards)]
            comunes = set.intersection(*[
                set(m.loc[c].index) for c in cards if c in m.index.get_level_values(0)]) \
                if any(c in m.index.get_level_values(0) for c in cards) else set()
            if not comunes:
                print(f'      {nom:<7} no common cells'); continue
            sub = m[m.index.get_level_values(1).isin(comunes)].groupby('gpu_label').median()
            orden = sub.sort_values()
            print(f'      {nom:<7} (n={len(comunes)}) ' + ' < '.join(
                f'{g.split(" (")[0]} {v:.1f}s' for g, v in orden.items()))
            nom_corto = [g.split(' (')[0] for g in orden.index]
            juntos = [f'{nom_corto[i]}~{nom_corto[i+1]}'
                      for i in range(len(orden) - 1)
                      if orden.iloc[i + 1] - orden.iloc[i] < 1.0]
            if juntos:
                print('              indistinguishable pairs (< 1 s): ' + ', '.join(juntos))
    print('\n== MEDIAN PER CARD over its own cells (not directly comparable across cards) ==')
    for nom, src in (('August', agosto), ('Current', nuevo)):
        m = src[ARMS[1]].groupby('gpu_label').agg(['median', 'size'])
        print(f'   {nom:<7} ' + '  '.join(
            f'{g.split(" (")[0]} {r["median"]:.1f}s(n={int(r["size"])})' for g, r in m.iterrows()))
    print('\nWritten all three CSVs in data/.')


if __name__ == '__main__':
    main()
