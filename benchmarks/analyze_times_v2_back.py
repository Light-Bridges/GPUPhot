#!/usr/bin/env python3
"""
Analyze Processing Times from GPUPhot Benchmark CSVs.

This script processes the CSV files generated by ``collect_times_from_elastic.py``
to produce publication-quality statistical analysis of the GPUPhot pipeline
performance.  It is designed to withstand the rigour expected by Q1 journals
such as *Astronomy and Computing*.

Pipeline
--------
1. **Load & Merge** -- combine multiple monthly CSV exports.
2. **Rename legacy columns** -- ``obid`` is actually OBLINEID (unique per image).
3. **Deduplicate** -- keep the most-recent run per (oblineid, gpu_name) pair.
4. **Filter timeouts** -- remove runs exceeding a configurable wall-clock
   threshold (default 300 s) that represent system artefacts, not algorithm
   performance.
5. **Derived columns** -- ``image_size``, ``python_ver_short``, ``n_pixels``.
6. **Cardinality summary** -- dataset composition at a glance.
7. **Robust descriptive statistics** -- median, IQR, 95 % bootstrap CI,
   P5/P95 percentiles, alongside mean and std for reference.
8. **Formal statistical tests** -- Mann-Whitney U for pairwise GPU and
   Python-version comparisons within each camera/image-size group.
9. **Scalability analysis** -- Spearman rank correlation (with *p*-value)
   between execution time and source count.
10. **Confounders report** -- GPU temperature, load, and free memory
    distributions per configuration.
11. **Figure generation** -- publication-ready plots (box-plots, violin
    plots, scatter, heatmaps) saved to ``benchmarks/figures/``.
12. **LaTeX table export** -- tables ready to ``\\input{}`` in the manuscript,
    saved to ``benchmarks/tables/``.

Usage
-----
::

    # Defaults: load all es_times_*_per_hit.csv in current dir
    python benchmarks/analyze_times.py

    # Custom files and timeout threshold
    python benchmarks/analyze_times.py --csv benchmarks/es_times_*.csv --timeout 600

    # Skip figure generation (text-only)
    python benchmarks/analyze_times.py --no-figures
"""

