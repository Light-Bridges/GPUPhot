def load_data(file_patterns: List[str]) -> pd.DataFrame:
    """Load and merge CSVs, expanding globs."""
    all_files: list[str] = []
    for pattern in file_patterns:
        found = glob.glob(pattern)
        if found:
            all_files.extend(found)
        elif "*" not in pattern and "?" not in pattern:
            all_files.append(pattern)

    all_files = sorted(set(all_files))
    if not all_files:
        print("Error: No input files found.")
        sys.exit(1)

    dfs = []
    for f in all_files:
        try:
            df = pd.read_csv(f)
            dfs.append(df)
            print(f"  Loaded {len(df):>7,} rows from {f}")
        except Exception as e:
            print(f"  Warning: Could not read {f}: {e}")

    if not dfs:
        print("Error: No valid data loaded.")
        sys.exit(1)

    return pd.concat(dfs, ignore_index=True)


def prepare_dataframe(df: pd.DataFrame, timeout_s: float) -> pd.DataFrame:
    """Rename, type-cast, deduplicate, filter timeouts, add derived columns."""

    # -- Rename legacy column: obid is actually OBLINEID
    if "obid" in df.columns:
        df = df.rename(columns={"obid": "oblineid"})

    # -- Ensure numeric types
    for col in ("execution_time", "n_sources_detected", "naxis1", "naxis2",
                "gpu_load", "gpu_mem_free", "gpu_mem_total", "gpu_mem_used", "gpu_temp"):
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")

    # -- Parse timestamps
    if "timestamp" in df.columns:
        df["timestamp"] = pd.to_datetime(df["timestamp"], errors="coerce", utc=True)

    n_raw = len(df)

    # -- Deduplicate: keep most-recent run per (oblineid, gpu_name)
    if "oblineid" in df.columns and "gpu_name" in df.columns:
        df = df.sort_values("timestamp").drop_duplicates(
            subset=["oblineid", "gpu_name"], keep="last"
        )
    n_deduped = len(df)

    # -- Filter timeouts / extreme values
    mask_timeout = df["execution_time"] <= timeout_s
    mask_valid = df["execution_time"].notna() & (df["execution_time"] > 0)
    df = df[mask_timeout & mask_valid].copy()
    n_clean = len(df)

    # -- Filter invalid GPU entries (error messages, not real GPUs)
    INVALID_GPU_NAMES = {"Error retrieving GPU info", "No GPUs found"}
    if "gpu_name" in df.columns:
        mask_valid_gpu = ~df["gpu_name"].isin(INVALID_GPU_NAMES)
        n_before_gpu = len(df)
        df = df[mask_valid_gpu].copy()
        n_invalid_gpu = n_before_gpu - len(df)
    else:
        n_invalid_gpu = 0

    print(f"\n  Raw records:      {n_raw:>7,}")
    print(f"  After dedup:      {n_deduped:>7,} (removed {n_raw - n_deduped:,} duplicates)")
    print(f"  After timeout:    {n_clean:>7,} (removed {n_deduped - n_clean:,} runs > {timeout_s:.0f} s)")
    print(f"  After GPU filter: {len(df):>7,} (removed {n_invalid_gpu:,} invalid GPU entries)")

    # -- Normalize camera names
    if "camera" in df.columns:
        atlas_cams = {"cam01", "cam02", "cam03", "cam04",
                      "cam01, cam02, cam03, cam04"}
        df.loc[df["camera"].isin(atlas_cams), "camera"] = "Atlas 4 cams"

    # -- Derived columns
    if "naxis1" in df.columns and "naxis2" in df.columns:
        has_dims = df["naxis1"].notna() & df["naxis2"].notna()
        df.loc[has_dims, "image_size"] = (
            df.loc[has_dims, "naxis1"].astype(int).astype(str) + "x"
            + df.loc[has_dims, "naxis2"].astype(int).astype(str)
        )
        df.loc[~has_dims, "image_size"] = "Unknown"
        df["n_pixels"] = df["naxis1"] * df["naxis2"]
    else:
        df["image_size"] = "Unknown"
        df["n_pixels"] = np.nan

    if "python_ver" in df.columns:
        df["python_ver_short"] = (
            df["python_ver"]
            .astype(str)
            .str.split("\n")
            .str[0]
            .str.split(" ")
            .str[0]
        )
    else:
        df["python_ver_short"] = "Unknown"

    return df


