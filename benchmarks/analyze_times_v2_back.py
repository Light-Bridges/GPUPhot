# ---------------------------------------------------------------------------
# 2. Robust descriptive statistics
# ---------------------------------------------------------------------------
def _bootstrap_ci(data: np.ndarray, n_boot: int = BOOTSTRAP_N,
                  ci: float = BOOTSTRAP_CI) -> tuple[float, float]:
    """Return (lower, upper) bootstrap CI for the median."""
    if len(data) < 2:
        m = np.median(data)
        return m, m
    rng = np.random.default_rng(42)
    medians = np.array(
        [np.median(rng.choice(data, size=len(data), replace=True)) for _ in range(n_boot)]
    )
    alpha = (1 - ci) / 2
    return float(np.percentile(medians, 100 * alpha)), float(
        np.percentile(medians, 100 * (1 - alpha))
    )


def analyze_performance(df: pd.DataFrame, min_group: int) -> pd.DataFrame:
    """Compute robust statistics per group. Returns the summary DataFrame."""
    gcols = valid_group_cols(df)
    if not gcols:
        print("Error: missing columns for grouping.")
        return pd.DataFrame()

    print("\n" + "=" * 70)
    print("2. ROBUST PERFORMANCE STATISTICS")
    print("=" * 70)

    records = []
    for name, grp in df.groupby(gcols):
        if len(grp) < min_group:
            continue
        t = grp["execution_time"].values
        s = grp["n_sources_detected"].dropna().values

        ci_lo, ci_hi = _bootstrap_ci(t)

        records.append(
            {
                **dict(zip(gcols, name if isinstance(name, tuple) else (name,))),
                "N": len(t),
                "median_s": np.median(t),
                "ci95_lo": ci_lo,
                "ci95_hi": ci_hi,
                "iqr_s": float(np.percentile(t, 75) - np.percentile(t, 25)),
                "p5_s": float(np.percentile(t, 5)),
                "p95_s": float(np.percentile(t, 95)),
                "mean_s": np.mean(t),
                "std_s": np.std(t, ddof=1) if len(t) > 1 else 0.0,
                "min_s": np.min(t),
                "max_s": np.max(t),
                "median_src": float(np.median(s)) if len(s) else np.nan,
                "mean_src": float(np.mean(s)) if len(s) else np.nan,
            }
        )

    summary = pd.DataFrame(records)
    if summary.empty:
        print("  No groups with sufficient data.")
        return summary

    summary = summary.sort_values(gcols)
    display_cols = gcols + [
        "N", "median_s", "ci95_lo", "ci95_hi", "iqr_s", "p5_s", "p95_s",
        "mean_s", "std_s", "median_src",
    ]
    with pd.option_context("display.max_rows", None, "display.width", 200, "display.float_format", "{:.2f}".format):
        print(summary[display_cols].to_string(index=False))

    return summary


# ---------------------------------------------------------------------------
# 3. Formal pairwise comparisons (Mann-Whitney U)
# ---------------------------------------------------------------------------
def pairwise_gpu_comparison(df: pd.DataFrame, min_group: int) -> None:
    """Compare GPUs within each (camera, image_size) group using Mann-Whitney U."""
    if not HAS_SCIPY:
        print("\n  [Skipped: scipy not installed]")
        return

    print("\n" + "=" * 70)
    print("3. PAIRWISE GPU COMPARISON (Mann-Whitney U)")
    print("=" * 70)
    print("  H0: distributions are identical.  Reject if p < 0.05.")
    print("-" * 70)

    workload_cols = ["camera", "filter", "image_size"]
    workload_cols = [c for c in workload_cols if c in df.columns]
    if not workload_cols or "gpu_name" not in df.columns:
        print("  Missing columns.")
        return

    results = []
    for wname, wgrp in df.groupby(workload_cols):
        gpus = wgrp["gpu_name"].unique()
        if len(gpus) < 2:
            continue
        for i in range(len(gpus)):
            for j in range(i + 1, len(gpus)):
                a = wgrp[wgrp["gpu_name"] == gpus[i]]["execution_time"].values
                b = wgrp[wgrp["gpu_name"] == gpus[j]]["execution_time"].values
                if len(a) < min_group or len(b) < min_group:
                    continue
                stat, pval = sp_stats.mannwhitneyu(a, b, alternative="two-sided")
                wlabel = ", ".join(map(str, wname)) if isinstance(wname, tuple) else str(wname)
                results.append({
                    "Workload": wlabel,
                    "GPU_A": gpus[i], "N_A": len(a), "Median_A": f"{np.median(a):.2f}",
                    "GPU_B": gpus[j], "N_B": len(b), "Median_B": f"{np.median(b):.2f}",
                    "U": f"{stat:.0f}", "p-value": f"{pval:.4g}",
                    "Sig": "***" if pval < 0.001 else ("**" if pval < 0.01 else ("*" if pval < 0.05 else "ns")),
                })

    if results:
        rdf = pd.DataFrame(results)
        with pd.option_context("display.max_rows", None, "display.width", 200):
            print(rdf.to_string(index=False))
    else:
        print("  No comparable GPU pairs found.")


def pairwise_python_comparison(df: pd.DataFrame, min_group: int) -> None:
    """Compare Python versions within each (gpu_name, camera, image_size) group."""
    if not HAS_SCIPY:
        return

    print("\n" + "=" * 70)
    print("4. PYTHON 3.8 vs 3.12 COMPARISON (Mann-Whitney U)")
    print("=" * 70)

    context_cols = ["gpu_name", "camera", "filter", "image_size"]
    context_cols = [c for c in context_cols if c in df.columns]
    if "python_ver_short" not in df.columns:
        print("  Missing python_ver_short column.")
        return

    results = []
    for cname, cgrp in df.groupby(context_cols):
        versions = cgrp["python_ver_short"].unique()
        if len(versions) < 2:
            continue
        for i in range(len(versions)):
            for j in range(i + 1, len(versions)):
                a = cgrp[cgrp["python_ver_short"] == versions[i]]["execution_time"].values
                b = cgrp[cgrp["python_ver_short"] == versions[j]]["execution_time"].values
                if len(a) < min_group or len(b) < min_group:
                    continue
                stat, pval = sp_stats.mannwhitneyu(a, b, alternative="two-sided")
                clabel = ", ".join(map(str, cname)) if isinstance(cname, tuple) else str(cname)
                results.append({
                    "Context": clabel,
                    "Py_A": versions[i], "N_A": len(a), "Median_A": f"{np.median(a):.2f}",
                    "Py_B": versions[j], "N_B": len(b), "Median_B": f"{np.median(b):.2f}",
                    "U": f"{stat:.0f}", "p-value": f"{pval:.4g}",
                    "Sig": "***" if pval < 0.001 else ("**" if pval < 0.01 else ("*" if pval < 0.05 else "ns")),
                })

    if results:
        rdf = pd.DataFrame(results)
        with pd.option_context("display.max_rows", None, "display.width", 200):
            print(rdf.to_string(index=False))
    else:
        print("  No comparable Python-version pairs found (need >= {} samples each).".format(min_group))


# ---------------------------------------------------------------------------
# 5. Scalability: Spearman correlation
# ---------------------------------------------------------------------------
def analyze_scalability(df: pd.DataFrame, min_group: int) -> None:
    """Spearman rank correlation between execution_time and n_sources_detected."""
    print("\n" + "=" * 70)
    print("5. SCALABILITY ANALYSIS (Spearman rho: Time vs Source Count)")
    print("=" * 70)
    if not HAS_SCIPY:
        print("  [Skipped: scipy not installed]")
        return

    gcols = valid_group_cols(df)
    clean = df.dropna(subset=["execution_time", "n_sources_detected"])

    results = []
    for name, grp in clean.groupby(gcols):
        if len(grp) < max(min_group, 10):
            continue
        rho, pval = sp_stats.spearmanr(grp["execution_time"], grp["n_sources_detected"])
        label = ", ".join(map(str, name)) if isinstance(name, tuple) else str(name)
        results.append({
            "Group": label,
            "N": len(grp),
            "Median_t(s)": f"{grp['execution_time'].median():.2f}",
            "Median_src": f"{grp['n_sources_detected'].median():.0f}",
            "Spearman_rho": f"{rho:.4f}",
            "p-value": f"{pval:.4g}",
            "Sig": "***" if pval < 0.001 else ("**" if pval < 0.01 else ("*" if pval < 0.05 else "ns")),
        })

    if results:
        rdf = pd.DataFrame(results).sort_values("N", ascending=False)
        with pd.option_context("display.max_rows", None, "display.width", 200):
            print(rdf.to_string(index=False))




# ---------------------------------------------------------------------------
# 6. Confounders report
# ---------------------------------------------------------------------------
def report_confounders(df: pd.DataFrame) -> None:
    """Report GPU temperature, load, and free memory distributions."""
    print("\n" + "=" * 70)
    print("6. CONFOUNDERS: GPU STATE AT PROCESSING TIME")
    print("=" * 70)

    confounder_cols = ["gpu_temp", "gpu_load", "gpu_mem_free", "gpu_mem_used"]
    available = [c for c in confounder_cols if c in df.columns and df[c].notna().any()]
    if not available:
        print("  No GPU state columns available.")
        return

    gpu_groups = ["gpu_name"]
    if "python_ver_short" in df.columns:
        gpu_groups.append("python_ver_short")

    for col in available:
        print(f"\n  --- {col} ---")
        stats = df.groupby(gpu_groups)[col].describe(percentiles=[0.05, 0.5, 0.95])
        with pd.option_context("display.max_rows", None, "display.width", 180, "display.float_format", "{:.1f}".format):
            print(stats.to_string())


# ---------------------------------------------------------------------------
# 7. Figure generation
# ---------------------------------------------------------------------------
def generate_figures(df: pd.DataFrame, outdir: str) -> None:
    """Generate publication-quality plots."""
    if not HAS_PLOT:
        print("\n  [Figures skipped: matplotlib/seaborn not installed]")
        return

    figdir = Path(outdir) / FIGURE_DIR
    figdir.mkdir(parents=True, exist_ok=True)
    sns.set_theme(style="whitegrid", font_scale=1.1)
    print(f"\n  Saving figures to {figdir}/")

    # -- Fig 1: Box plot of execution time by GPU, faceted by camera
    cameras = df["camera"].unique() if "camera" in df.columns else []
    # Filter to cameras with enough data
    camera_counts = df["camera"].value_counts()
    top_cameras = camera_counts[camera_counts >= 50].index.tolist()

    if top_cameras and "gpu_name" in df.columns:
        plot_df = df[df["camera"].isin(top_cameras)].copy()
        # Shorten GPU names for readability
        plot_df["gpu_short"] = plot_df["gpu_name"].str.replace("NVIDIA ", "")

        fig, ax = plt.subplots(figsize=(14, 7))
        sns.boxplot(
            data=plot_df, x="camera", y="execution_time", hue="gpu_short",
            showfliers=False, ax=ax,
        )
        ax.set_ylabel("End-to-End Latency (s)")
        ax.set_xlabel("Camera")
        ax.set_title("Execution Time Distribution by Camera and GPU")
        ax.legend(title="GPU", bbox_to_anchor=(1.02, 1), loc="upper left")
        plt.tight_layout()
        fig.savefig(figdir / "boxplot_time_by_camera_gpu.pdf", dpi=300)
        fig.savefig(figdir / "boxplot_time_by_camera_gpu.png", dpi=150)
        plt.close(fig)
        print(f"    boxplot_time_by_camera_gpu.pdf")

    # -- Fig 2: Violin plot of execution time by image size
    if "n_pixels" in df.columns and "gpu_name" in df.columns:
        plot_df = df.dropna(subset=["n_pixels"]).copy()
        plot_df["mpixels"] = plot_df["n_pixels"] / 1e6
        # Bin into size categories
        bins = [0, 5, 10, 25, 50, 200]
        labels = ["<5 MP", "5-10 MP", "10-25 MP", "25-50 MP", ">50 MP"]
        plot_df["size_cat"] = pd.cut(plot_df["mpixels"], bins=bins, labels=labels)
        plot_df["gpu_short"] = plot_df["gpu_name"].str.replace("NVIDIA ", "")

        fig, ax = plt.subplots(figsize=(12, 6))
        sns.violinplot(
            data=plot_df, x="size_cat", y="execution_time", hue="gpu_short",
            cut=0, inner="quartile", ax=ax,
        )
        ax.set_ylabel("End-to-End Latency (s)")
        ax.set_xlabel("Image Size Category")
        ax.set_title("Execution Time Distribution by Image Size and GPU")
        ax.legend(title="GPU", bbox_to_anchor=(1.02, 1), loc="upper left")
        plt.tight_layout()
        fig.savefig(figdir / "violin_time_by_size_gpu.pdf", dpi=300)
        fig.savefig(figdir / "violin_time_by_size_gpu.png", dpi=150)
        plt.close(fig)
        print(f"    violin_time_by_size_gpu.pdf")

    # -- Fig 3: Scatter time vs n_sources (coloured by GPU)
    if "n_sources_detected" in df.columns:
        plot_df = df.dropna(subset=["n_sources_detected"]).copy()
        plot_df["gpu_short"] = plot_df["gpu_name"].str.replace("NVIDIA ", "")

        fig, ax = plt.subplots(figsize=(10, 7))
        for gpu, gdf in plot_df.groupby("gpu_short"):
            ax.scatter(gdf["n_sources_detected"], gdf["execution_time"],
                       alpha=0.15, s=8, label=gpu)
        ax.set_xlabel("Number of Sources Detected")
        ax.set_ylabel("End-to-End Latency (s)")
        ax.set_title("Execution Time vs Source Density")
        ax.legend(title="GPU", markerscale=4)
        ax.set_xscale("log")
        plt.tight_layout()
        fig.savefig(figdir / "scatter_time_vs_sources.pdf", dpi=300)
        fig.savefig(figdir / "scatter_time_vs_sources.png", dpi=150)
        plt.close(fig)
        print(f"    scatter_time_vs_sources.pdf")

    # -- Fig 4: Latency vs image size (median + CI)
    if "n_pixels" in df.columns:
        plot_df = df.dropna(subset=["n_pixels"]).copy()
        plot_df["gpu_short"] = plot_df["gpu_name"].str.replace("NVIDIA ", "")

        fig, ax = plt.subplots(figsize=(10, 6))
        for gpu, gdf in plot_df.groupby("gpu_short"):
            grp = gdf.groupby("image_size").agg(
                median_t=("execution_time", "median"),
                q25=("execution_time", lambda x: np.percentile(x, 25)),
                q75=("execution_time", lambda x: np.percentile(x, 75)),
                mpix=("n_pixels", "first"),
            ).reset_index().sort_values("mpix")
            ax.errorbar(
                grp["mpix"] / 1e6, grp["median_t"],
                yerr=[grp["median_t"] - grp["q25"], grp["q75"] - grp["median_t"]],
                fmt="o-", label=gpu, capsize=3, markersize=5,
            )
        ax.set_xlabel("Image Size (Megapixels)")
        ax.set_ylabel("Median End-to-End Latency (s)")
        ax.set_title("Latency Scaling with Image Size")
        ax.legend(title="GPU")
        ax.set_xscale("log")
        plt.tight_layout()
        fig.savefig(figdir / "latency_vs_megapixels.pdf", dpi=300)
        fig.savefig(figdir / "latency_vs_megapixels.png", dpi=150)
