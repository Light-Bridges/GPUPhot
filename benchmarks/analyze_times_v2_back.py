# 8. LaTeX table export
# ---------------------------------------------------------------------------
def export_latex_tables(summary: pd.DataFrame, df: pd.DataFrame, outdir: str) -> None:
    """Export key tables in LaTeX format."""
    tbldir = Path(outdir) / TABLE_DIR
    tbldir.mkdir(parents=True, exist_ok=True)
    print(f"\n  Saving LaTeX tables to {tbldir}/")

    if summary.empty:
        print("  No summary data to export.")
        return

    # -- Table: Performance summary (for the manuscript)
    # Select most representative rows: group by (camera, image_size, gpu_name, python_ver_short)
    key_cols = ["gpu_name", "python_ver_short", "camera", "image_size"]
    key_cols = [c for c in key_cols if c in summary.columns]
    export_cols = key_cols + ["N", "median_s", "ci95_lo", "ci95_hi", "iqr_s", "p5_s", "p95_s", "median_src"]
    available = [c for c in export_cols if c in summary.columns]

    tex = summary[available].to_latex(
        index=False, float_format="%.2f", na_rep="--",
        caption="Robust performance statistics for key camera and GPU configurations. "
                "Median end-to-end latency with 95\\% bootstrap confidence interval, "
                "interquartile range (IQR), and 5th/95th percentiles.",
        label="tab:performance_robust",
    )
    outpath = tbldir / "table_performance_robust.tex"
    outpath.write_text(tex)
    print(f"    {outpath.name}")

    # -- Table: Dataset composition
    if "camera" in df.columns and "gpu_name" in df.columns:
        comp = df.groupby(["gpu_name", "python_ver_short", "camera", "image_size"]).agg(
            N=("execution_time", "count"),
            unique_images=("oblineid", "nunique") if "oblineid" in df.columns else ("execution_time", "count"),
        ).reset_index()
        comp = comp[comp["N"] >= 10].sort_values(["gpu_name", "camera"])

        tex2 = comp.to_latex(
            index=False,
            caption="Dataset composition: number of benchmark measurements per configuration after deduplication and timeout filtering.",
            label="tab:dataset_composition",
        )
        outpath2 = tbldir / "table_dataset_composition.tex"
        outpath2.write_text(tex2)
        print(f"    {outpath2.name}")


