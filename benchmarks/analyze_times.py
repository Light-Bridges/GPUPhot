#!/usr/bin/env python3
"""
Analyze Processing Times from GPUPhot Benchmark CSVs.

This script processes the CSV files generated by `collect_times_from_elastic.py` to provide statistical insights
into the performance of the GPUPhot pipeline. It helps identify bottlenecks, compare hardware performance,
and verify algorithmic scalability.

Key Analysis Sections:
----------------------
1. **Cardinality Summary**:
   - Lists unique values for categorical columns (e.g., Instruments, Cameras, Filters, Drivers).
   - Useful for verifying the diversity of the dataset and spotting configuration anomalies.

2. **Performance Analysis (Execution Time & Sources)**:
   - Aggregates data by key factors: GPU Model, Python Version, Camera, Filter, and Image Size.
   - Computes statistics (Mean, Std, Min, Max) for:
     * `execution_time`: Total processing time per image.
     * `n_sources_detected`: Complexity of the image (star density).
   - Helps compare performance across different hardware and observing conditions.

3. **Anomaly Analysis (Outliers)**:
   - Detects execution times that deviate significantly (> Mean + 2*Std) within their specific group.
   - Lists the top 20 slowest executions to help pinpoint specific bad runs.
   - Shows the temporal distribution of outliers to identify systemic issues (e.g., network outages at specific hours).

4. **Correlation Analysis (Scalability)**:
   - Measures the relationship between `execution_time` and `n_sources_detected`.
   - **Correlation**: Pearson coefficient. Values near 0 indicate perfect scalability (time is independent of star count).
   - **Slope (s/src)**: Estimated seconds added per additional source. Ideally close to 0.

Usage Examples:
  # Analyze a single file:
  python benchmarks/analyze_times.py --csv benchmarks/es_times_dec2025_per_hit.csv

  # Analyze multiple files (e.g., different months):
  python benchmarks/analyze_times.py --csv benchmarks/es_times_*.csv

  # Analyze specific files:
  python benchmarks/analyze_times.py --csv run1.csv run2.csv
"""

import argparse
import pandas as pd
import sys
import glob

def parse_args():
    p = argparse.ArgumentParser(description="Analyze GPUPhot processing times CSV")
    p.add_argument("--csv", nargs='+', default=["es_times_*_per_hit.csv"],
                   help="Path to input CSV file(s). Supports wildcards (e.g., results_*.csv)")
    return p.parse_args()

def load_data(file_patterns):
    """
    Load and combine multiple CSV files into a single DataFrame.
    
    Args:
        file_patterns (list): List of file paths or glob patterns.
        
    Returns:
        pd.DataFrame: Combined dataframe containing all records.
    """
    all_files = []
    for pattern in file_patterns:
        # Expand wildcards (globbing)
        files = glob.glob(pattern)
        if not files:
            # If glob returns nothing, maybe it's a literal filename that doesn't exist or just a string
            # We keep it to let pandas try or fail, but usually glob handles literal paths too.
            if '*' not in pattern and '?' not in pattern:
                all_files.append(pattern)
        else:
            all_files.extend(files)
    
    # Remove duplicates
    all_files = sorted(list(set(all_files)))
    
    if not all_files:
        print("Error: No input files found.")
        sys.exit(1)

    dfs = []
    for f in all_files:
        try:
            df = pd.read_csv(f)
            dfs.append(df)
            print(f"Loaded {len(df)} rows from {f}")
        except Exception as e:
            print(f"Warning: Could not read {f}: {e}")
    
    if not dfs:
        print("Error: No valid data loaded.")
        sys.exit(1)
        
    return pd.concat(dfs, ignore_index=True)

def print_cardinality(df, columns):
    """
    Print the number of unique values for selected categorical columns.
    Useful for understanding the dataset composition.
    """
    print("\n" + "="*60)
    print("CARDINALITY SUMMARY (Unique Values)")
    print("="*60)
    for col in columns:
        if col in df.columns:
            unique_vals = df[col].dropna().unique()
            unique_count = len(unique_vals)
            print(f"{col:<15}: {unique_count:>4} unique values")
            if unique_count < 20 and unique_count > 0:
                # Print values in a compact way
                val_str = ", ".join(map(str, unique_vals))
                print(f"  Values: [{val_str}]")
        else:
            # print(f"{col}: [Column not found]")
            pass

def analyze_performance(df):
    """
    Group data by hardware/software/workload configuration and calculate performance statistics.
    
    Returns:
        list: The list of column names used for grouping.
    """
    print("\n" + "="*60)
    print("PERFORMANCE ANALYSIS (Execution Time & Sources by Hardware/Software/Workload)")
    print("="*60)
    
    # Create a combined column for image size to handle binning implicitly
    if 'naxis1' in df.columns and 'naxis2' in df.columns:
        df['image_size'] = df['naxis1'].astype(str) + "x" + df['naxis2'].astype(str)
    else:
        print("Warning: 'naxis1' or 'naxis2' columns missing. Skipping size grouping.")
        df['image_size'] = 'Unknown'
    
    # Clean up python_ver to be more readable (take first line if multiline)
    if 'python_ver' in df.columns:
        df['python_ver_short'] = df['python_ver'].astype(str).apply(lambda x: x.split('\n')[0].split(' ')[0] if x else 'Unknown')
    else:
        df['python_ver_short'] = 'Unknown'

    # Group by GPU, Python Version, Camera, Filter, and Image Size
    group_cols = ['gpu_name', 'python_ver_short', 'camera', 'filter', 'image_size']
    # Filter out groups that don't exist or have nulls
    valid_cols = [c for c in group_cols if c in df.columns]
    
    if not valid_cols:
        print("Error: Missing necessary columns for grouping.")
        return None

    # Ensure numeric types for aggregation
    df['execution_time'] = pd.to_numeric(df['execution_time'], errors='coerce')
    df['n_sources_detected'] = pd.to_numeric(df['n_sources_detected'], errors='coerce')

    grouped = df.groupby(valid_cols)
    
    # Calculate stats for execution_time AND n_sources_detected
    # We use a dictionary to specify aggregations per column
    agg_dict = {
        'execution_time': ['count', 'mean', 'std', 'min', 'max'],
        'n_sources_detected': ['mean', 'std', 'min', 'max']
    }
    
    stats = grouped.agg(agg_dict).round(2)
    
    # Sort by GPU name for better readability
    if 'gpu_name' in stats.index.names:
        stats = stats.sort_index(level='gpu_name')
        
    # Ensure all rows are printed
    with pd.option_context('display.max_rows', None, 'display.max_columns', None, 'display.width', 1000):
        print(stats)
    
    return valid_cols

def analyze_anomalies(df, group_cols):
    """
    Identify and list execution time outliers.
    An outlier is defined as a value > Mean + 2*StdDev within its specific group.
    """
    print("\n" + "="*60)
    print("ANOMALY ANALYSIS (Outliers > Mean + 2*Std)")
    print("="*60)
    
    if 'execution_time' not in df.columns:
        return

    # Ensure numeric types
    df['execution_time'] = pd.to_numeric(df['execution_time'], errors='coerce')
    
    # Calculate mean and std per group
    grouped = df.groupby(group_cols)['execution_time'].agg(['mean', 'std'])
    
    # Join stats back to original dataframe
    merged = df.join(grouped, on=group_cols, rsuffix='_group')
    
    # Define threshold: Mean + 2*Std
    # We use 2 sigma as a basic outlier detection
    merged['threshold'] = merged['mean'] + 2 * merged['std']
    
    # Filter outliers
    outliers = merged[merged['execution_time'] > merged['threshold']].copy()
    
    if outliers.empty:
        print("No significant outliers found (all within 2 std dev).")
        return

    print(f"Found {len(outliers)} outliers out of {len(df)} records ({len(outliers)/len(df)*100:.1f}%).")
    print("Top 20 Slowest Executions:")
    
    # Select relevant columns for display
    display_cols = ['timestamp', 'execution_time', 'threshold', 'n_sources_detected'] + group_cols
    # Filter columns that actually exist
    display_cols = [c for c in display_cols if c in outliers.columns]
    
    # Sort by execution time descending
    top_outliers = outliers.sort_values('execution_time', ascending=False).head(20)
    
    with pd.option_context('display.max_rows', None, 'display.max_columns', None, 'display.width', 1000):
        print(top_outliers[display_cols].to_string(index=False))
        
    # Temporal distribution of outliers
    if 'timestamp' in outliers.columns:
        print("\nOutliers by Hour (Temporal Distribution):")
        try:
            outliers['dt'] = pd.to_datetime(outliers['timestamp'])
            print(outliers['dt'].dt.floor('H').value_counts().sort_index())
        except Exception:
            print("Could not parse timestamps for temporal analysis.")

def analyze_sources_correlation(df, group_cols):
    """
    Calculate correlation between execution time and number of sources detected.
    Also computes the slope (seconds per source) to estimate scalability.
    """
    print("\n" + "="*60)
    print("CORRELATION ANALYSIS (Impact of Source Density on Time)")
    print("="*60)
    print("  * Correlation: Pearson coeff (-1 to 1). Near 0 means time is independent of source count.")
    print("  * Slope: Approx. seconds added per source. Low slope = good scalability.")
    print("-" * 60)

    if 'n_sources_detected' not in df.columns or 'execution_time' not in df.columns:
        print("Missing columns for correlation analysis.")
        return

    # Ensure numeric types (already done in analyze_performance but good to be safe)
    df['n_sources_detected'] = pd.to_numeric(df['n_sources_detected'], errors='coerce')
    df['execution_time'] = pd.to_numeric(df['execution_time'], errors='coerce')
    
    # Drop rows with missing values for these calculations
    clean_df = df.dropna(subset=group_cols + ['n_sources_detected', 'execution_time'])
    
    grouped = clean_df.groupby(group_cols)
    
    results = []
    for name, group in grouped:
        if len(group) < 2:
            corr = float('nan')
            slope = 0.0
        else:
            corr = group['execution_time'].corr(group['n_sources_detected'])
            # Linear regression slope (simple approximation: cov(x,y) / var(x))
            if group['n_sources_detected'].std() > 0:
                 slope = group['execution_time'].cov(group['n_sources_detected']) / group['n_sources_detected'].var()
            else:
                 slope = 0.0

        # Format the group name tuple into a string
        if isinstance(name, tuple):
            group_name = ", ".join(map(str, name))
        else:
            group_name = str(name)

        row = {
            'Group': group_name,
            'Count': len(group),
            'Corr': round(corr, 4),
            'Slope (s/src)': f"{slope:.6f}",
            'Avg Sources': round(group['n_sources_detected'].mean(), 1),
            'Avg Time (s)': round(group['execution_time'].mean(), 3)
        }
        results.append(row)
    
    res_df = pd.DataFrame(results)
    if not res_df.empty:
        # Sort by count descending to show most relevant groups first
        # Reorder columns for display
        cols_order = ['Group', 'Count', 'Avg Time (s)', 'Avg Sources', 'Corr', 'Slope (s/src)']
        with pd.option_context('display.max_rows', None, 'display.max_columns', None, 'display.width', 1000):
            print(res_df[cols_order].sort_values('Count', ascending=False).to_string(index=False))
    else:
        print("No sufficient data for correlation analysis.")

def main():
    args = parse_args()
    
    # Load and combine data
    df = load_data(args.csv)
    print(f"\nTotal records loaded: {len(df)}")

    # -- Filter invalid GPU entries (error messages, not real GPUs)
    INVALID_GPU_NAMES = {"Error retrieving GPU info", "No GPUs found"}
    if "gpu_name" in df.columns:
        n_before = len(df)
        df = df[~df["gpu_name"].isin(INVALID_GPU_NAMES)].copy()
        n_removed = n_before - len(df)
        if n_removed:
            print(f"  Removed {n_removed:,} records with invalid GPU names")

    # 1. Cardinality
    cols_to_check = [
        'instrume', 'inmodel', 'camera', 'naxis1', 'naxis2', 'obid', 'orid', 
        'dateproc', 'inserial', 'telescop', 'filter', 'dateobs', 'exptime', 'object',
        'gpu_name', 'gpu_driver', 'gpu_id', 'gpu_load', 'gpu_mem_free', 
        'gpu_mem_total', 'gpu_mem_used', 'gpu_temp', 'arch', 'cupy_ver', 
        'kernel', 'os', 'os_ver', 'processor', 'python_ver'
    ]
    print_cardinality(df, cols_to_check)

    # 2. Performance Analysis (Time)
    group_cols = analyze_performance(df)

    # 3. Anomaly Analysis
    if group_cols:
        analyze_anomalies(df, group_cols)

    # 4. Correlation Analysis (Time vs Sources)
    if group_cols:
        analyze_sources_correlation(df, group_cols)

if __name__ == "__main__":
    main()
